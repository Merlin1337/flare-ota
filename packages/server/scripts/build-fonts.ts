// Regenerates src/fonts.ts: the dashboard's typeface, embedded so the Worker serves it itself
// (no third-party font CDN, CSP stays 'self'). Plus Jakarta Sans, SIL Open Font License 1.1.
//   node scripts/build-fonts.ts
import { readFileSync, writeFileSync } from "node:fs";

const file = new URL("../node_modules/@fontsource-variable/plus-jakarta-sans/files/plus-jakarta-sans-latin-wght-normal.woff2", import.meta.url);
const base64 = readFileSync(file).toString("base64");
writeFileSync(
  new URL("../src/fonts.ts", import.meta.url),
  `// Generated by scripts/build-fonts.ts. Plus Jakarta Sans (variable, latin), SIL Open Font License 1.1,\n// Copyright 2020 The Plus Jakarta Sans Project Authors. See NOTICE.md.\nexport const JAKARTA_WOFF2 = "${base64}";\n`,
);
console.log(`src/fonts.ts: ${base64.length} base64 chars`);
